def guide_for(url_name):
    """url name এর গাইড (ধাপসহ, **গাঢ়** রূপান্তরিত) — না থাকলে None।"""
    g = GUIDES.get(url_name)
    if not g:
        return None
    return {
        'key': url_name,
        'lead': g.get('lead', ''),
        'steps': [_rich(s) for s in g['steps']],
        'tip': _rich(g['tip']) if g.get('tip') else '',
        'open': g.get('open', True),
    }
